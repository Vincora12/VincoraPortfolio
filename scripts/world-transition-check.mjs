import assert from 'node:assert/strict';
import { build } from 'esbuild';

const compiled = await build({ stdin: { contents: `
  export { completeWorldTransition } from './src/engine/worldTransition';
  export { seedWorld, emptyLedger } from './src/engine/world';
  export { SYNC_REWARD_DAYS } from './src/engine/syncRewards';
  export { generateFirstMon } from './src/engine/characterGenerator';
  export { initialHealthState } from './src/engine/health';
  export { neutralPersonality, EMPTY_NOVELTY } from './src/engine/signals';
`, resolveDir: process.cwd(), loader: 'ts' }, bundle: true, write: false, platform: 'node', format: 'esm', logLevel: 'silent' });
const m = await import(`data:text/javascript;base64,${Buffer.from(compiled.outputFiles[0].text).toString('base64')}`);
const makeMon = (seed, node) => m.generateFirstMon({ input: { day: 1, health: m.initialHealthState(), personality: m.neutralPersonality(), moodHistory: [], cultural: {}, novelty: m.EMPTY_NOVELTY, mindlineDepth: 0, bond: 50, dataConfidence: 50, activeDays: 1, branchCount: 0 }, mindlineNodeId: node, originNodeId: null, lineageNames: [], seed }).record;
const a = makeMon(1001,'node-a'); const b = makeMon(1002,'node-b'); const c = makeMon(1003,'node-c');
const world = m.seedWorld(a,1);
const ledger = { ...m.emptyLedger(), recurringMotifs: ['fixture motif'], setups: [{ id:'setup-a', summary:'fixture setup', status:'open', day:1 }] };
const before = JSON.stringify({world,ledger,a,b});
const tune = m.completeWorldTransition({kind:'evolution',world,ledger,previous:a,record:b,day:2});
assert.equal(tune.world.id,world.id);
assert.equal(tune.record.worldId,world.id);
assert.equal(tune.previous.worldId,world.id, 'legacy previous link filled only at actual transition');
assert.deepEqual(tune.world.worldCulturalDna,world.worldCulturalDna);
assert.equal(tune.world.identity,world.identity);
assert.equal(tune.ledger,ledger);
assert.equal(tune.worldHistory.length,0);
assert.equal(JSON.stringify({world,ledger,a,b}),before,'transition never mutates original data');
const tuneAgain = m.completeWorldTransition({kind:'evolution',world:tune.world,ledger,previous:tune.previous,record:tune.record,day:2});
assert.equal(tuneAgain.world.canon.length,tune.world.canon.length,'same TUNE canon id not duplicated');
const rise = m.completeWorldTransition({kind:'mega-evolution',world:tune.world,ledger,previous:tune.record,record:c,day:7});
assert.notEqual(rise.world.id,world.id);
assert.equal(rise.record.worldId,rise.world.id);
assert.equal(rise.previous.worldId,world.id);
assert.equal(rise.worldHistory.length,1);
assert.equal(rise.worldHistory[0].world.id,world.id);
assert.equal(rise.worldHistory[0].nextWorldId,rise.world.id);
assert.deepEqual(rise.worldHistory[0].ledger,ledger);
assert.equal(rise.ledger.setups.length,0);
assert.deepEqual(rise.worldHistory[0].world.canon.slice(0,tune.world.canon.length),tune.world.canon,'all old canon preserved');
const replay = m.completeWorldTransition({kind:'mega-evolution',world:rise.world,ledger:rise.ledger,worldHistory:rise.worldHistory,previous:rise.previous,record:rise.record,day:7});
assert.equal(replay.worldHistory.length,1,'RISE replay does not archive current World');
assert.equal(replay.world.id,rise.world.id);
const tuneInNewWorld = m.completeWorldTransition({kind:'evolution',world:rise.world,ledger:rise.ledger,worldHistory:rise.worldHistory,previous:rise.record,record:makeMon(1004,'node-d'),day:9});
assert.equal(tuneInNewWorld.world.id,rise.world.id,'several forms share the new World');
assert.deepEqual(tuneInNewWorld.worldHistory,rise.worldHistory);
const legacy = m.completeWorldTransition({kind:'evolution',world:null,ledger:m.emptyLedger(),previous:a,record:b,day:2});
assert.equal(legacy.previous.worldId,legacy.record.worldId,'missing legacy World gets one deterministic same-world fallback');
const wished = {...c,data:{...c.data,user_wish:'fixture wish'}};
assert.equal(m.completeWorldTransition({kind:'mega-evolution',world,ledger,previous:a,record:wished,day:30}).record.data.user_wish,'fixture wish','Wish preserved without reinterpretation');
assert.deepEqual(m.SYNC_REWARD_DAYS,{evolution:2,'mega-evolution':7,wish:30},'existing costs unchanged');
console.log('PASS: TUNE same World, RISE new World, archive/canon/ledger preservation, idempotency, multiple forms, legacy fallback, Wish unchanged, costs2/7/30 unchanged. No images, AI, graph or production state touched.');
